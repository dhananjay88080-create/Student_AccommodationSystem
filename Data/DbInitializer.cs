using Microsoft.AspNetCore.Identity;
using Microsoft.EntityFrameworkCore;
using StudentAccommodationSystem.Models;
namespace StudentAccommodationSystem.Data;
public static class DbInitializer
{
 public static async Task SeedAsync(IServiceProvider services)
 {
  var db=services.GetRequiredService<ApplicationDbContext>(); var userManager=services.GetRequiredService<UserManager<ApplicationUser>>(); var roleManager=services.GetRequiredService<RoleManager<IdentityRole>>();
  try { await db.Database.MigrateAsync(); } catch { /* First-run migration is generated by the setup command. */ }
  foreach(var role in new[]{"Administrator","Owner","Student"}) if(!await roleManager.RoleExistsAsync(role)) await roleManager.CreateAsync(new IdentityRole(role));
  // Retire the obsolete Manager role and remove its assignments so only three roles remain.
  var obsoleteManagerRole = await roleManager.FindByNameAsync("Manager");
  if (obsoleteManagerRole != null)
  {
   foreach (var managerUser in await userManager.GetUsersInRoleAsync("Manager")) await userManager.RemoveFromRoleAsync(managerUser, "Manager");
   await roleManager.DeleteAsync(obsoleteManagerRole);
  }
  async Task<ApplicationUser> User(string email,string name,string role){ var u=await userManager.FindByEmailAsync(email); if(u!=null)return u; u=new ApplicationUser{UserName=email,Email=email,EmailConfirmed=true,FullName=name,IsActive=true}; var r=await userManager.CreateAsync(u,$"{role}@12345"); if(r.Succeeded) await userManager.AddToRoleAsync(u,role); return u; }
  var admin=await User("admin@accommodation.local","System Administrator","Administrator"); var owner=await User("owner@accommodation.local","Demo Owner","Owner"); var student=await User("student@accommodation.local","Demo Student","Student");
  if(!await db.OwnerProfiles.AnyAsync(x=>x.UserId==owner.Id)) db.OwnerProfiles.Add(new OwnerProfile{UserId=owner.Id,BusinessName="Demo Rentals"});
  if(!await db.StudentProfiles.AnyAsync(x=>x.UserId==student.Id)) db.StudentProfiles.Add(new StudentProfile{UserId=student.Id,StudentNumber="STU-001",University="Demo University"});
  await db.SaveChangesAsync();
  // No sample properties or rooms are seeded. Add real properties manually through the Owner dashboard.
 }
}
